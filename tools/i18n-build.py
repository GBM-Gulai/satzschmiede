"""Merge lang/catalog.json + lang/src/*.json into tr.js (helper-language translations).

  python tools/i18n-build.py

tr.js sets window.TR = { pt: {english: translation}, es: {...}, fr: {...} }.
Warns about missing translations and about placeholders ({0}, {name}, <b>) that don't match the English.
"""
import json, re, glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGS = ["pt", "es", "fr"]
# Short strings the extractor skips (too short to be safe as a general key) but which are real card texts.
EXTRA = {"I": {"pt": "eu", "es": "yo", "fr": "je"}}

cat = json.load(open(os.path.join(ROOT, "lang", "catalog.json"), encoding="utf-8"))
src = {l: {} for l in LANGS}
for f in sorted(glob.glob(os.path.join(ROOT, "lang", "src", "*.json"))):
    data = json.load(open(f, encoding="utf-8"))
    for l in LANGS:
        src[l].update(data.get(l, {}))

TOKENS = re.compile(r"\{\w+\}|<\/?b>|<\/?i>|<br>")
out, problems = {}, 0
for l in LANGS:
    tr = {}
    missing = []
    for i, item in enumerate(cat):
        t = src[l].get(str(i))
        if t is None:
            missing.append(i)
            continue
        en = item["en"]
        if sorted(TOKENS.findall(en)) != sorted(TOKENS.findall(t)):
            print(f"[{l}] {i}: placeholders differ\n   en: {en}\n   {l}: {t}")
            problems += 1
        if t != en:
            tr[en] = t
    for en, by in EXTRA.items():
        tr[en] = by[l]
    out[l] = tr
    print(f"{l}: {len(tr)} translations, {len(missing)} left in English")
    if "-v" in sys.argv and missing:
        print("   untranslated:", ", ".join(map(str, missing)))

js = "/* Generated by tools/i18n-build.py from lang/ - do not edit by hand. */\nwindow.TR = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n"
open(os.path.join(ROOT, "tr.js"), "w", encoding="utf-8").write(js)
print(f"Wrote tr.js ({len(js.encode('utf-8')) // 1024} KB), {problems} placeholder warnings")
